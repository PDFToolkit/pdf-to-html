<?php

declare(strict_types=1);

namespace PDF\Html\Tests;

use PDF\Html\PdfToHtml;
use PDF\Html\Reading\ContentInstructionReader;
use PDF\Html\Reading\ReadingBudget;
use PDF\Html\Reading\ReadingException;
use PDF\Html\Reading\ReadingLimits;
use PDF\Reading\FileBytes;
use PDF\Syntax\Object\NameType;
use PDF\Syntax\Object\IntegerType;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class InlineImageReadingTest extends TestCase
{
    public function testBracesAreOrdinaryBytesInContentOperatorNames(): void
    {
        $instructions = $this->instructions('BX 1 Future{Operator} EX q Q');
        self::assertSame(['BX', 'Future{Operator}', 'EX', 'q', 'Q'], array_column($instructions, 'operator'));
    }

    public function testExactRawLengthDoesNotInterpretEiInsideSamples(): void
    {
        $instructions = $this->instructions("BI /W 4 /H 1 /BPC 8 /CS /G ID  EI  EI q Q");
        self::assertSame(['BI', 'q', 'Q'], array_column($instructions, 'operator'));
        self::assertSame(' EI ', $instructions[0]->inlineImage?->bytes);
        self::assertEquals(new NameType('DeviceGray'), $instructions[0]->inlineImage->dictionary->get('ColorSpace'));
    }

    public function testCrLfDelimiterAndPackedRowsAreReadExactly(): void
    {
        $instructions = $this->instructions("BI /W 3 /H 2 /BPC 1 /CS /G ID\r\n\x80\x40\r\nEI q Q");
        self::assertSame("\x80\x40", $instructions[0]->inlineImage?->bytes);
        self::assertSame('q', $instructions[1]->operator);
    }

    /** @return iterable<string, array{string, string}> */
    public static function encodedSamples(): iterable
    {
        yield 'ASCIIHex with explicit end' => ['/AHx', '20454920>'];
        yield 'ASCII85 with explicit end' => ['/A85', '+?p3j~>'];
        yield 'RunLength literal containing EI' => ['/RL', "\x03 EI \x80"];
        $flate = gzcompress(' EI ');
        if ($flate === false) {
            throw new \RuntimeException('Could not construct the independent zlib sample.');
        }
        yield 'Flate with verified zlib end' => ['/Fl', $flate];
        // Nine-bit clear, literal bytes 32/69/73/32, EOD; generated by an independent bit packer.
        yield 'LZW with explicit EOD' => ['/LZW', hex2bin('800808a4910404') ?: throw new \RuntimeException('Invalid sample')];
    }

    #[DataProvider('encodedSamples')]
    public function testFilterEndpointsPreserveFollowingOperators(string $filter, string $encoded): void
    {
        $instructions = $this->instructions('BI /W 4 /H 1 /BPC 8 /CS /G /F ' . $filter . ' ID ' . $encoded . ' EI q Q');
        self::assertSame($encoded, $instructions[0]->inlineImage?->bytes);
        self::assertSame(['BI', 'q', 'Q'], array_column($instructions, 'operator'));
    }

    public function testJpegAppDataCannotTerminateTheInlineImage(): void
    {
        $original = file_get_contents(__DIR__ . '/Fixtures/inline-gray.jpg');
        self::assertIsString($original);
        $payload = " EI \xff\xd9";
        $jpeg = substr($original, 0, 2) . "\xff\xef" . pack('n', strlen($payload) + 2) . $payload . substr($original, 2);
        $instructions = $this->instructions('BI /W 80 /H 40 /BPC 8 /CS /G /F /DCT ID ' . $jpeg . ' EI q Q');
        self::assertSame($jpeg, $instructions[0]->inlineImage?->bytes);
        self::assertSame('q', $instructions[1]->operator);
    }

    /** @return iterable<string, array{string}> */
    public static function malformedImages(): iterable
    {
        yield 'truncated pixels' => ['BI /W 8 /H 1 /BPC 8 /CS /G ID abc EI'];
        yield 'EI inside extra pixels is not a delimiter' => ['BI /W 1 /H 1 /BPC 8 /CS /G ID abc EI'];
        yield 'no EI' => ['BI /W 1 /H 1 /BPC 8 /CS /G ID a '];
        yield 'EI token prefix is not EI' => ['BI /W 1 /H 1 /BPC 8 /CS /G ID a EInject'];
        yield 'truncated Flate' => ["BI /W 1 /H 1 /BPC 8 /CS /G /F /Fl ID \x78\x9c EI"];
        yield 'truncated RunLength packet' => ["BI /W 1 /H 1 /BPC 8 /CS /G /F /RL ID \x7f EI"];
        yield 'RunLength without end' => ["BI /W 1 /H 1 /BPC 8 /CS /G /F /RL ID \xffa"];
        yield 'ASCIIHex without end' => ['BI /W 1 /H 1 /BPC 8 /CS /G /F /AHx ID 61 EI'];
        yield 'ASCII85 invalid final group' => ['BI /W 1 /H 1 /BPC 8 /CS /G /F /A85 ID !~> EI'];
        yield 'JPEG missing EOI' => ["BI /W 1 /H 1 /BPC 8 /CS /G /F /DCT ID \xff\xd8\xff\xda\x00\x02a EI"];
        yield 'LZW undefined first code' => ["BI /W 1 /H 1 /BPC 8 /CS /G /F /LZW ID \xff\xff EI"];
        yield 'invalid LZW early change' => ['BI /W 1 /H 1 /BPC 8 /CS /G /F /LZW /DP <</EarlyChange 2>> ID abc EI'];
        yield 'unsupported endpoint' => ['BI /W 1 /H 1 /BPC 1 /CS /G /F /CCF ID ambiguous EI bytes EI'];
        yield 'duplicate decoded key' => ['BI /W 1 /#57 1 /H 1 /BPC 8 /CS /G ID a EI'];
        yield 'overridden indirect parameter' => ['BI /W 1 /Width 3 0 R /H 1 /BPC 8 /CS /G ID a EI'];
        yield 'indirect parameter' => ['BI /W 1 0 R /H 1 /BPC 8 /CS /G ID a EI'];
        yield 'filter arrays must be flat' => ['BI /W 1 /H 1 /BPC 8 /CS /G /F [[/AHx]] ID 61> EI'];
        yield 'unknown raw colour-space width' => ['BI /W 1 /H 1 /BPC 8 /CS /Unknown ID abc EI'];
        yield 'oversized samples' => ['BI /W 9223372036854775807 /H 1 /BPC 16 /CS /RGB ID a EI'];
    }

    #[DataProvider('malformedImages')]
    public function testTruncatedAndAmbiguousDataFailDeterministically(string $bytes): void
    {
        $this->expectException(ReadingException::class);
        $this->instructions($bytes);
    }

    /** @return iterable<string, array{string}> */
    public static function competingParameters(): iterable
    {
        $short = '/W 1 /H 1 /BPC 8 /CS /G /F /AHx /L 3';
        $full = '/Width 999 /Height 99 /BitsPerComponent 16 /ColorSpace /RGB /Filter 17 /Length 999';
        yield 'short before full' => [$short . ' ' . $full];
        yield 'short after full' => [$full . ' ' . $short];
    }

    #[DataProvider('competingParameters')]
    public function testAbbreviationsTakePrecedenceWithoutMovingTheImageEndpoint(string $parameters): void
    {
        $instructions = $this->instructions('BI ' . $parameters . ' ID 61> EI q Q');
        self::assertSame(['BI', 'q', 'Q'], array_column($instructions, 'operator'));
        $image = $instructions[0]->inlineImage;
        self::assertNotNull($image);
        self::assertSame('61>', $image->bytes);
        self::assertEquals(new IntegerType(1), $image->dictionary->get('Width'));
        self::assertEquals(new IntegerType(1), $image->dictionary->get('Height'));
        self::assertEquals(new IntegerType(8), $image->dictionary->get('BitsPerComponent'));
        self::assertEquals(new IntegerType(3), $image->dictionary->get('Length'));
        self::assertEquals(new NameType('DeviceGray'), $image->dictionary->get('ColorSpace'));
        self::assertEquals(new NameType('ASCIIHexDecode'), $image->dictionary->get('Filter'));
    }

    public function testBoundaryInflationUsesTheCumulativeContentBudget(): void
    {
        $encoded = gzcompress(str_repeat('a', 1024));
        self::assertIsString($encoded);
        $reader = new ContentInstructionReader(new ReadingBudget(new ReadingLimits(maximumContentBytes: 512)));
        $this->expectException(ReadingException::class);
        $this->expectExceptionMessage('cumulative source content');
        iterator_to_array($reader->read('BI /W 1024 /H 1 /BPC 8 /CS /G /F /Fl ID ' . $encoded . ' EI'));
    }

    public function testIndependentPdfDerivesImagesPlaceholdersAndFollowingText(): void
    {
        $bytes = file_get_contents(__DIR__ . '/Fixtures/inline-images.pdf');
        self::assertIsString($bytes);
        $result = (new PdfToHtml())->convert(new FileBytes($bytes), 'inline-images.pdf');
        self::assertStringContainsString('Text after all inline images', $result->html);
        self::assertSame(12, substr_count($result->html, '<img '));
        self::assertSame(12, substr_count($result->html, 'width="27" height="13"'));
        self::assertCount(4, $result->assets);
        self::assertCount(4, array_filter($result->diagnostics, static fn ($item): bool => $item->code === 'source-interpretation' && str_contains($item->message, 'placeholder')));
    }

    /** @return list<\PDF\Html\Reading\ContentInstruction> */
    private function instructions(string $bytes): array
    {
        return iterator_to_array((new ContentInstructionReader(new ReadingBudget(new ReadingLimits())))->read($bytes), false);
    }
}
