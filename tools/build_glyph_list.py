"""Reproduce the immutable Adobe glyph tables from unchanged, pinned upstream data."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "resources/glyph-lists"
TARGET = ROOT / "src/Reading/AdobeGlyphList.php"


def entries(filename):
    result = []
    for line in (SOURCE / filename).read_text(encoding="ascii").splitlines():
        if not line or line.startswith("#"):
            continue
        name, values = line.split(";")
        scalars = [int(value, 16) for value in values.split()]
        assert all(0 <= value <= 0x10FFFF and not 0xD800 <= value <= 0xDFFF for value in scalars)
        text = "".join("\\u{%X}" % value for value in scalars)
        result.append("        '%s' => \"%s\"," % (name, text))
    return "\n".join(result)


parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
for entry in manifest["files"]:
    assert hashlib.sha256((SOURCE / entry["path"]).read_bytes()).hexdigest() == entry["sha256"], entry["path"]
output = '''<?php

declare(strict_types=1);

namespace PDF\\Html\\Reading;

/** Generated by tools/build_glyph_list.py. Adobe data: resources/glyph-lists/LICENSE.md. */
final readonly class AdobeGlyphList
{
    /** @var array<string, string> */
    private const GLYPHS = [
%s
    ];
    /** @var array<string, string> */
    private const DINGBATS = [
%s
    ];

    public function character(string $name, bool $zapfDingbats = false): ?string
    {
        return ($zapfDingbats ? self::DINGBATS[$name] ?? null : null) ?? self::GLYPHS[$name] ?? null;
    }
}
''' % (entries("glyphlist.txt"), entries("zapfdingbats.txt"))
if args.check:
    assert TARGET.read_bytes() == output.encode("utf-8"), "AdobeGlyphList.php must be regenerated"
else:
    TARGET.write_bytes(output.encode("utf-8"))
print("Adobe glyph tables and upstream hashes verified")
